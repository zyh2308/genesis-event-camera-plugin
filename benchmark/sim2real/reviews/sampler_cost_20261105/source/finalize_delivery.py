"""Create a new, small, auditable delivery after all acceptance jobs finish.

Standard library only.  Never imports a simulator, changes a production file,
or contacts a server.  The default root is this script's server-run directory.
Only NEW root/delivery/ and NEW root/delivery.tar.gz are created.  An existing
delivery or archive is an error; partial failures are deliberately preserved.
Run this script only after all evidence-producing processes have finished.
"""
from __future__ import annotations

import argparse
import datetime
import gzip
import hashlib
import json
from pathlib import Path
import shutil
import sys
import tarfile


GEOMETRY = 'genesis_event_plugin/gpu_geometry.py'
ARRAY_SUFFIXES = {'.npy', '.npz', '.h5', '.hdf5'}
MAX_LOG_BYTES = 1024 * 1024
MAX_ALL_LOG_BYTES = 8 * 1024 * 1024


def sha256(path):
    result = hashlib.sha256()
    with path.open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            result.update(block)
    return result.hexdigest()


def receipt(path, root=None):
    info = path.stat()
    return {
        'path': str(path.relative_to(root)) if root else str(path),
        'size_bytes': info.st_size,
        'sha256': sha256(path),
    }


def read_json(path):
    return json.loads(path.read_text(encoding='utf-8'))


def write_json_new(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('x', encoding='utf-8', newline='\n') as stream:
        json.dump(value, stream, indent=2, ensure_ascii=False, allow_nan=False)
        stream.write('\n')


def checked_copy(source, target):
    """Refuse symlinks, overwrites, and source changes during a copy."""
    if source.is_symlink() or not source.is_file():
        raise RuntimeError(f'Expected a regular source file: {source}')
    before = receipt(source)
    target.parent.mkdir(parents=True, exist_ok=True)
    with source.open('rb') as inp, target.open('xb') as out:
        shutil.copyfileobj(inp, out, length=1024 * 1024)
    if receipt(source) != before or sha256(target) != before['sha256']:
        raise RuntimeError(f'Source changed while copied: {source}')
    return before


def release_inventory(root, include_bytecode=False):
    if not root.is_dir() or root.is_symlink():
        raise RuntimeError(f'Expected a static release directory: {root}')
    files = {}
    excluded_runtime_cache = []
    for path in sorted(root.rglob('*')):
        if path.is_symlink():
            raise RuntimeError(f'Symlink in release is not accepted: {path}')
        if not path.is_file():
            continue
        relative = path.relative_to(root).as_posix()
        if not include_bytecode and ('__pycache__' in path.relative_to(root).parts
                                     or path.suffix in {'.pyc', '.pyo'}):
            excluded_runtime_cache.append(relative)
            continue
        files[relative] = receipt(path, root)
    return files, excluded_runtime_cache


def is_rpc_server(path):
    stem = path.stem.lower().replace('_', '').replace('-', '')
    return 'rpc' in stem and 'server' in stem


def tar_metadata(info):
    # Normalize archive metadata without changing any source or payload bytes.
    info.uid = info.gid = 0
    info.uname = info.gname = ''
    info.mtime = 0
    info.mode = 0o755 if info.isdir() else 0o644
    return info


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parent)
    parser.add_argument('--base-release', type=Path)
    parser.add_argument('--include-bytecode', action='store_true',
                        help='Also require generated bytecode/cache files to match')
    args = parser.parse_args()
    root = args.root.resolve(strict=True)
    base = (args.base_release or root.parent/'simulator_efficiency_comparison_20261105c/release_candidate_static').resolve(strict=True)
    candidate = (root/'candidate_release').resolve(strict=True)
    delivery = root/'delivery'
    archive = root/'delivery.tar.gz'
    if delivery.exists() or archive.exists() or delivery.is_symlink() or archive.is_symlink():
        raise FileExistsError('Refusing to replace an existing delivery or archive')
    if not candidate.is_relative_to(root) or candidate == root:
        raise RuntimeError('Candidate must be a separate static release inside this run')

    quality_path = root/'full_quality_summary.json'
    benchmark_path = root/'benchmark_summary.json'
    variability_path = root/'normal_mode_event_variability.json'
    formal_path = root/'formal_loader_gate/formal_loader_results.json'
    quality = read_json(quality_path)
    benchmark = read_json(benchmark_path)
    variability = read_json(variability_path)
    formal = read_json(formal_path)
    if not (quality.get('status') == 'complete'
            and quality.get('all_exact') is True
            and quality.get('actual_formal_loaders_passed') is True):
        raise RuntimeError('Full deterministic physical/formal quality gates are incomplete or failed')
    if not (benchmark.get('status') == 'complete'
            and benchmark.get('validation', {}).get('passed') is True):
        raise RuntimeError('Benchmark summary is incomplete or failed validation')
    if variability.get('status') != 'complete':
        raise RuntimeError('Normal-mode event variability report is incomplete')
    if formal.get('passed') is not True:
        raise RuntimeError('The actual formal loader receipt did not pass')
    prerequisites = [receipt(path, root) for path in
                     (quality_path, benchmark_path, variability_path, formal_path)]

    base_files, base_cache = release_inventory(base, args.include_bytecode)
    candidate_files, candidate_cache = release_inventory(candidate, args.include_bytecode)
    if GEOMETRY not in base_files or GEOMETRY not in candidate_files:
        raise RuntimeError('Both static releases must contain actual gpu_geometry.py')
    if set(base_files) != set(candidate_files):
        raise RuntimeError('Static release file sets differ: '+json.dumps({
            'base_only': sorted(set(base_files)-set(candidate_files)),
            'candidate_only': sorted(set(candidate_files)-set(base_files))}))
    changed = [name for name in base_files
               if base_files[name]['sha256'] != candidate_files[name]['sha256']
               or base_files[name]['size_bytes'] != candidate_files[name]['size_bytes']]
    if set(changed)-{GEOMETRY}:
        raise RuntimeError('A release file outside gpu_geometry.py changed: '+repr(changed))
    if GEOMETRY not in changed:
        raise RuntimeError('Candidate geometry is unchanged; do not package a different claimed optimization')

    # All checks above are read-only.  Every write below is to a new delivery
    # directory, followed by exclusive creation of the new archive.
    delivery.mkdir(exist_ok=False)
    (delivery/'source').mkdir()
    (delivery/'release/genesis_event_plugin').mkdir(parents=True)
    (delivery/'evidence').mkdir()
    embedded_originals = {}
    excluded_rpc_sources = []
    for path in sorted(root.glob('*.py')):
        if is_rpc_server(path):
            excluded_rpc_sources.append(receipt(path, root))
            continue
        checked_copy(path, delivery/'source'/path.name)
        embedded_originals[path.relative_to(root).as_posix()] = 'source/'+path.name
    checked_copy(candidate/GEOMETRY, delivery/'release'/GEOMETRY)
    write_json_new(delivery/'release/manifest.json', {
        'schema': 'isolated_geometry_delta_release_v1',
        'base_release': str(base), 'candidate_release': str(candidate),
        'only_allowed_changed_file': GEOMETRY, 'actual_changed_files': changed,
        'all_other_release_files_byte_identical': True,
        'base_files': list(base_files.values()),
        'candidate_files': list(candidate_files.values()),
        'runtime_cache_excluded_from_release_comparison': not args.include_bytecode,
        'excluded_base_runtime_cache': base_cache,
        'excluded_candidate_runtime_cache': candidate_cache,
        'embedded_release_is_delta_only': True,
        'requires_exact_base_release_manifest': True,
        'automatic_production_promotion_performed': False,
    })

    evidence_files = set(root.glob('*.json')) | set(root.glob('*.csv'))
    comparison_dir = root/'gate_comparison'
    if not comparison_dir.is_dir():
        raise FileNotFoundError('Expected gate_comparison evidence directory')
    evidence_files.update(comparison_dir.glob('*.json'))
    evidence_files.add(formal_path)
    excluded_full_traces = []
    for path in sorted(evidence_files):
        relative = path.relative_to(root).as_posix()
        # Comparison reports may contain "trace" in their names and must stay
        # embedded, including the first failed report.  Exclude only full raw
        # traces here; nested gate_long traces are not selected in the first
        # place and are indexed by the external scan below.
        if path.name.lower() in {'trace.json', 'full_trace.json'} or path.stem.lower().startswith('fullgate_longtrace'):
            excluded_full_traces.append(relative)
            continue
        checked_copy(path, delivery/'evidence'/relative)
        embedded_originals[relative] = 'evidence/'+relative

    logs = []
    # Index every raw array and full trace under the run, including build/input
    # subdirectories.  Never copy these arrays into the lightweight archive.
    # The delivery itself is the only recursively excluded run directory.
    external = []
    log_bytes = 0
    for path in sorted(root.rglob('*')):
        if path.is_relative_to(delivery):
            continue
        if path.is_symlink():
            raise RuntimeError(f'Symlink in the private run must be reviewed: {path}')
        if not path.is_file() or path == archive:
            continue
        relative = path.relative_to(root).as_posix()
        is_array = path.suffix.lower() in ARRAY_SUFFIXES
        is_trace = ('trace' in path.stem.lower() and path.suffix.lower() == '.json'
                    and relative not in embedded_originals)
        if is_array or is_trace:
            item = receipt(path, root)
            item.update(server_path=str(path),
                        reason='raw_array' if is_array else 'full_trace',
                        embedded=False)
            external.append(item)
        if path.suffix.lower() != '.log':
            continue
        item = receipt(path, root)
        item['server_path'] = str(path)
        if item['size_bytes'] > MAX_LOG_BYTES or log_bytes+item['size_bytes'] > MAX_ALL_LOG_BYTES:
            item.update(reason='log_exceeds_light_delivery_budget', embedded=False)
            external.append(item)
            logs.append(item)
            continue
        target = delivery/'evidence'/(relative+'.gz')
        target.parent.mkdir(parents=True, exist_ok=True)
        with path.open('rb') as inp, target.open('xb') as raw:
            with gzip.GzipFile(filename='', mode='wb', fileobj=raw, mtime=0) as out:
                shutil.copyfileobj(inp, out, length=1024 * 1024)
        if receipt(path, root)['sha256'] != item['sha256']:
            raise RuntimeError(f'Log changed during packaging: {path}')
        log_bytes += item['size_bytes']
        item.update(embedded=True, embedded_path=str(target.relative_to(delivery)),
                    compression='gzip_lossless')
        logs.append(item)

    write_json_new(delivery/'evidence/external_artifacts.json', {
        'root': str(root), 'hash': 'sha256',
        'recursive_exclusion': ['delivery/'],
        'raw_arrays_are_indexed_even_in_build_and_input_subdirectories': True,
        'artifacts': external,
    })
    write_json_new(delivery/'DELIVERY_SCOPE.json', {
        'schema': 'sampler_optimization_light_delivery_v1',
        'created_utc': datetime.datetime.now(datetime.timezone.utc).isoformat(),
        'run_root': str(root), 'prerequisites': prerequisites,
        'source_rule': 'Exact server-side top-level *.py bytes, excluding RPC server source; no local replacement',
        'excluded_rpc_sources': excluded_rpc_sources,
        'server_builder_v1_and_any_versioned_failed_gate_sources_preserved': True,
        'prior_reports_are_copied_without_rewriting': True,
        'excluded_full_trace_names_from_evidence_selection': excluded_full_traces,
        'embedded_original_files': embedded_originals, 'logs': logs,
        'log_raw_byte_budgets': {'per_file': MAX_LOG_BYTES, 'aggregate': MAX_ALL_LOG_BYTES},
        'quality_scope': 'Exact equality is conditional on the tested deterministic runtime and fixed fixtures; not universal/default-mode equality',
        'normal_mode_raw_byte_equality_is_a_separate_report': True,
        'normal_mode_all_cross_raw_byte_equal': variability.get('all_cross_raw_byte_equal'),
        'v2e_quality_matched': False,
        'v2e_same_temporal_density_claimed': False,
        'v2e_minimum63_is_separate_numerical_step_control': True,
        'genesis_rendering_included_in_efficiency': False,
        'three_timing_repeats_are_not_a_confidence_interval': True,
        'training_modified_or_started': False,
        'frozen_release_modified': False,
        'production_promotion_performed': False,
        'gpu_lease_modified_or_finished': False,
        'archive_target': str(archive),
        'artifact_index_self_hash': 'Not embedded: a cryptographic manifest cannot hash itself; archive hash is printed externally',
    })

    # Reverify static releases and the prerequisite receipts after all copying.
    if release_inventory(base, args.include_bytecode)[0] != base_files:
        raise RuntimeError('Frozen base changed during packaging')
    if release_inventory(candidate, args.include_bytecode)[0] != candidate_files:
        raise RuntimeError('Candidate release changed during packaging')
    for item in prerequisites:
        if receipt(root/item['path'], root) != item:
            raise RuntimeError('A required summary changed during packaging')
    payload = [receipt(path, delivery) for path in sorted(delivery.rglob('*')) if path.is_file()]
    write_json_new(delivery/'artifact_index.json', {
        'schema': 'delivery_payload_sha256_index_v1',
        'root': 'delivery', 'hash': 'sha256',
        'excludes_self_to_avoid_circular_hash': True, 'files': payload,
    })
    # The exclusive-create mode guarantees an existing archive is never replaced.
    with archive.open('xb') as raw:
        with gzip.GzipFile(filename='', mode='wb', fileobj=raw, mtime=0) as compressed:
            with tarfile.open(fileobj=compressed, mode='w') as tar:
                tar.add(delivery, arcname='delivery', recursive=True, filter=tar_metadata)
    result = receipt(archive)
    result.update(status='complete', embedded_files=len(payload)+1,
                  external_artifacts=len(external),
                  preferred_archive_size_bytes=1024*1024,
                  within_preferred_archive_size=archive.stat().st_size <= 1024*1024,
                  evidence_never_dropped_to_meet_size_goal=True)
    print(json.dumps(result, indent=2), flush=True)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
